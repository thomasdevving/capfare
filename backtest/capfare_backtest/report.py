"""Charts and the Markdown report (docs/PRICING.md)."""
from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

INK = "#1F2328"
ACCENT = "#2B6CB0"
LOSS = "#B42318"
plt.rcParams.update({"font.size": 10, "axes.edgecolor": INK, "axes.labelcolor": INK, "xtick.color": INK,
                     "ytick.color": INK, "axes.spines.top": False, "axes.spines.right": False})


def chart_weekly(summary: dict, title: str, path: Path):
    wk = np.array(summary["weekly_pnl_eur"])
    fig, ax = plt.subplots(figsize=(7, 2.6), dpi=150)
    ax.bar(range(len(wk)), wk, color=[ACCENT if x >= 0 else LOSS for x in wk], width=0.85)
    ax.axhline(0, color=INK, lw=0.8)
    ax.set_xlabel("week (synthetic)")
    ax.set_ylabel("vault P&L, €")
    ax.set_title(title, loc="left", fontsize=10)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def chart_dist(summary: dict, title: str, path: Path):
    x = np.array(summary["pnl_per_policy_dist_eur"])
    fig, ax = plt.subplots(figsize=(7, 2.6), dpi=150)
    ax.hist(x, bins=60, color=ACCENT)
    ax.axvline(x.mean(), color=INK, lw=1, ls="--")
    ax.set_xlabel("P&L per policy, € (premium net of fee minus payout)")
    ax.set_ylabel("policies")
    ax.set_title(title, loc="left", fontsize=10)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def chart_sensitivity(rows: list[dict], key: str, title: str, path: Path):
    fig, ax = plt.subplots(figsize=(7, 2.6), dpi=150)
    for prod, color in (("cap", ACCENT), ("drop", INK)):
        rs = [r for r in rows if r["product"] == prod]
        ax.plot([r[key] for r in rs], [r["return"] for r in rs], marker="o", color=color, label=prod)
    ax.axhline(0, color=LOSS, lw=0.8)
    ax.set_xlabel(key.replace("_", " "))
    ax.set_ylabel("vault return on premium")
    ax.legend(frameon=False)
    ax.set_title(title, loc="left", fontsize=10)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def fmt_pct(x):
    return f"{x * 100:.0f}%"


def write_markdown(path: Path, res: dict, img_rel: str):
    cap, drop = res["cap"], res["drop"]
    lines = [
        "# Pricing and backtest",
        "",
        "> **All numbers on this page come from SYNTHETIC price paths** generated by",
        "> `backtest/capfare_backtest/data.py`. They show that the method works and how sensitive",
        "> the vaults are to buyer behaviour. They are not evidence about real airline prices.",
        "> Re-run with real data via `CsvSource` before any non-testnet use.",
        "",
        f"Generated by `python -m capfare_backtest.cli run` (seed {res['seed']}, {res['flights']} flights,",
        f"{res['buyers_per_flight']} buyers per flight, informed share {fmt_pct(res['informed_share'])}).",
        "",
        "## Method",
        "",
        "1. Generate per-flight fare paths for the covered fare class over 120 days, every 6 hours:",
        "   fare-bucket closures driven by load factor and time (upward drift toward departure),",
        "   bursts of bucket changes (volatility clusters), short promotions, sell-outs of the",
        "   cheapest class, and seasonal flights.",
        "2. Simulate buyers per flight: uninformed, informed (buy only when momentum or availability",
        "   signals are high, then book at the worst moment for the vault), breakage (never book),",
        "   and refundable-fare cancellers (payout voided by the final status check).",
        "3. Price every sale with the exact on-chain formula (`formula.py` is an integer port of",
        "   `contracts/core`, checked against shared test vectors), apply activation delay,",
        "   deductible, max payout, per-flight exposure caps and the sold-out premium refund.",
        "4. Calibrate the public parameters: signal multipliers from payout ratios per bucket",
        "   (shrunk toward 1.0), moneyness slope by least squares, base table = expected payout per",
        "   (price, days-to-departure) cell divided by a target loss ratio.",
        "5. Search deductible × max payout × target loss ratio; keep sets whose median premium on",
        "   tickets up to €300 is ≤ €10 and whose vault return is positive; prefer larger max payouts.",
        "",
        "The two products are priced and capitalised **independently**.",
        "",
    ]
    for name, key, s, best in (("Price Cap", "cap", cap, res["cap_best"]), ("Drop Guarantee", "drop", drop, res["drop_best"])):
        lines += [
            f"## {name}",
            "",
            f"Chosen: deductible €{best['deductible'] / 100:.0f}, max payout €{best['max_payout'] / 100:.0f},"
            f" target loss ratio {best['target_lr']:.2f}.",
            "",
            "| Metric | Value |",
            "|---|---|",
            f"| Policies simulated | {s['policies']} |",
            f"| Median premium (all / tickets ≤ €300) | €{s['median_premium_eur']:.2f} / €{s['median_premium_le_300_eur']:.2f} |",
            f"| 90th percentile premium | €{s['p90_premium_eur']:.2f} |",
            f"| Claim rate (payout > 0) | {fmt_pct(s['claim_rate'])} |",
            f"| Loss ratio (payouts / premiums) | {s['loss_ratio']:.2f} |",
            f"| Vault return on premium (after 5% fee) | {s['vault_return_on_premium']:+.2f} |",
            f"| Break-even premium / max payout | {s['break_even_premium_over_max_payout']:.3f} |",
            f"| Average premium / max payout | {s['avg_premium_over_max_payout']:.3f} |",
            f"| Worst week / worst 4 weeks | €{s['worst_week_eur']:.0f} / €{s['worst_month_eur']:.0f} |",
            "",
            f"![{name} weekly P&L]({img_rel}/{key}_weekly.png)",
            "",
            f"![{name} P&L per policy]({img_rel}/{key}_dist.png)",
            "",
        ]
    lines += ["## Sensitivity to buyer selection", "",
              "| Product | Informed share | Breakage | Loss ratio | Vault return |", "|---|---|---|---|---|"]
    for r in res["sensitivity"]:
        lines.append(f"| {r['product']} | {fmt_pct(r['informed_share'])} | {fmt_pct(r['breakage'])} | {r['loss_ratio']:.2f} | {r['return']:+.2f} |")
    lines += ["", f"![Sensitivity to informed buyers]({img_rel}/sensitivity_informed.png)", "",
              f"![Sensitivity to breakage]({img_rel}/sensitivity_breakage.png)", "",
              "## Required capital", "",
              "Full collateralisation already locks every policy's max payout. The extra loss buffer",
              "below is the 52-week cumulative loss exceeded with 1% probability (bootstrap of the",
              "simulated per-policy P&L).", "",
              "| Product | Policies / week | Collateral (live policies) | Loss buffer (1% ruin) | P(loss after a year) |",
              "|---|---|---|---|---|"]
    for c in res["capital"]:
        lines.append(f"| {c['product']} | {c['policies_per_week']} | €{c['collateral_eur']:,.0f} | €{abs(c['loss_buffer_eur']):,.0f} | {fmt_pct(c['p_loss_after_year'])} |")
    lines += ["", "## Combined view (secondary)", "",
              f"Cap + drop together: premiums €{cap['premium_total_eur'] + drop['premium_total_eur']:,.0f},"
              f" payouts €{cap['payout_total_eur'] + drop['payout_total_eur']:,.0f}. No hedge between the products is assumed;",
              "they sit in separate vaults.", "",
              "## Limitations", "",
              "- Synthetic paths: the shape of real airline fare curves, promotion frequency and",
              "  sell-out timing will differ. Parameters must be re-fitted on real observations.",
              "- Buyer behaviour is modelled, not observed. The informed-buyer share and breakage are the",
              "  biggest drivers (see the sensitivity table); the real values are unknown.",
              "- Vault utilisation is held at 30% when pricing; the on-chain utilisation surcharge is not",
              "  exercised by the simulation.",
              "- OTA prices are modelled as the airline price ±3%; payout uses min(index, paid).",
              "- In this model informed Drop buyers (buying while prices fall) pay the high momentum",
              "  multiplier, so they do not raise the loss ratio; real informed behaviour may differ.",
              "- FX between EUR and USDC is fixed per policy at purchase and not simulated.",
              "- Group collusion beyond the informed-buyer model (many accounts on one flight) is limited",
              "  by per-user and per-flight caps but not simulated explicitly.",
              ""]
    path.write_text("\n".join(lines))
