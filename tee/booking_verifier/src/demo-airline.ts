/**
 * Demo airline backend (demo deployments only): a mocked "manage booking" page that the
 * status-check path logs into, plus a generator for DKIM-signed fixture confirmation
 * emails. Fixture emails are signed with an ephemeral key under the selector
 * "capfare-fixture"; only demo deployments resolve that selector to the ephemeral key.
 * Every fixture is visibly marked as a synthetic test booking.
 */
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { dkimSign } from "mailauth";
import type { BookingStatus, Refundability } from "@capfare/shared";
import type { ParsedBooking, StatusResult } from "./airlines/types.ts";
import { parseKlmText } from "./airlines/klm.ts";

export const FIXTURE_SELECTOR = "capfare-fixture";

export interface FixtureInput {
  booking_ref?: string;
  last_name?: string;
  flight_number: string;
  departure_date: string; // YYYY-MM-DD
  origin: string;
  destination: string;
  fare_label: string; // "Economy Light"
  paid_price_minor: number;
  refundable: Refundability;
  booked_at: Date;
  from_domain?: string;
  subject_prefix?: string;
}

const MON = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

export function fixtureText(f: FixtureInput, ref: string, last: string): string {
  const [y, m, d] = f.departure_date.split("-").map(Number);
  const refText = f.refundable === "non_refundable" ? "This ticket is non-refundable." : f.refundable === "refundable" ? "This is a fully refundable ticket." : "";
  const eur = (f.paid_price_minor / 100).toFixed(2);
  return [
    "SYNTHETIC TEST BOOKING - generated by CapFare for demos and tests. Not issued by any airline.",
    "",
    "Your booking is confirmed",
    "",
    `Booking code: ${ref}`,
    `Passenger: ${last.toUpperCase()}/TEST MR`,
    "",
    "Flight",
    `${f.flight_number} · ${d} ${MON[m - 1]} ${y} · Amsterdam (${f.origin}) → Barcelona (${f.destination}) · ${f.fare_label}`,
    "",
    `Total price: EUR ${eur}`,
    refText,
    "",
  ].join("\r\n");
}

export class DemoKeys {
  readonly privatePem: string;
  readonly dnsRecord: string;
  constructor() {
    const { privateKey, publicKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
    this.privatePem = privateKey.export({ type: "pkcs1", format: "pem" }).toString();
    this.dnsRecord = `v=DKIM1; k=rsa; p=${publicKey.export({ type: "spki", format: "der" }).toString("base64")}`;
  }
}

export async function makeFixtureEml(f: FixtureInput, keys: DemoKeys, signDomain = "klm.com"): Promise<{ eml: string; booking_ref: string; last_name: string }> {
  const ref = f.booking_ref ?? randomBytes(4).toString("hex").toUpperCase().replace(/[^A-Z0-9]/g, "X").slice(0, 6).padEnd(6, "Q");
  const last = f.last_name ?? "Tester";
  const fromDomain = f.from_domain ?? signDomain;
  const body = fixtureText(f, ref, last);
  const msg = [
    `From: KLM test fixture <noreply@${fromDomain}>`,
    "To: traveller@example.org",
    `Subject: ${f.subject_prefix ?? ""}Booking confirmation ${ref} (synthetic test)`,
    `Date: ${f.booked_at.toUTCString().replace("GMT", "+0000")}`,
    `Message-ID: <${randomBytes(8).toString("hex")}@${fromDomain}>`,
    "MIME-Version: 1.0",
    "Content-Type: text/plain; charset=utf-8",
    "Content-Transfer-Encoding: 8bit",
    "",
    body,
  ].join("\r\n");
  const s = await dkimSign(msg, {
    signatureData: [{ signingDomain: signDomain, selector: FIXTURE_SELECTOR, privateKey: keys.privatePem }],
    headerList: "from:to:subject:date:message-id",
  });
  return { eml: s.signatures + msg, booking_ref: ref, last_name: last };
}

/** DNS resolver override for demo deployments: only the fixture selector is served. */
export function demoResolver(keys: DemoKeys, fallback?: (n: string, rr: string) => Promise<unknown>) {
  return async (name: string, rr: string) => {
    if (rr === "TXT" && name.startsWith(`${FIXTURE_SELECTOR}._domainkey.`)) return [[keys.dnsRecord]];
    if (fallback) return fallback(name, rr);
    const e = new Error(`no record for ${name}`) as Error & { code: string };
    e.code = "ENOTFOUND";
    throw e;
  };
}

/** Mocked manage-booking backend. */
export class DemoAirline {
  private bookings = new Map<string, { last: string; status: BookingStatus; text: string }>();

  register(ref: string, last: string, text: string) {
    this.bookings.set(ref.toUpperCase(), { last: last.toLowerCase(), status: "active", text });
  }

  setStatus(ref: string, status: BookingStatus) {
    const b = this.bookings.get(ref.toUpperCase());
    if (!b) throw new Error("unknown booking");
    b.status = status;
  }

  /** Renders the manage-booking HTML the enclave would read over TLS. */
  page(ref: string, last: string): string | null {
    const b = this.bookings.get(ref.toUpperCase());
    if (!b || b.last !== last.toLowerCase()) return null;
    const statusText = b.status === "cancelled" ? "Cancelled" : "Confirmed";
    return `<html><body><h1>Manage your booking</h1><p class="status">Booking status: ${statusText}</p><pre>${b.text}</pre></body></html>`;
  }

  async checkStatus(ref: string, last: string): Promise<StatusResult> {
    const html = this.page(ref, last);
    if (!html) throw new Error("booking not found for this reference and last name");
    const status: BookingStatus = /Booking status:\s*Cancelled/i.test(html) ? "cancelled" : /Booking status:\s*Confirmed/i.test(html) ? "active" : "unknown";
    const text = /<pre>([\s\S]*)<\/pre>/.exec(html)?.[1] ?? "";
    const booking = parseKlmText(text) as ParsedBooking;
    if (!booking) throw new Error("could not read booking page");
    return { status, booking };
  }
}
